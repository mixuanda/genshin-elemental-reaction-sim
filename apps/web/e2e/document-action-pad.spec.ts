test('old file remains unchanged; editing saves a reopenable unverified copy without a simulation',async({page})=>{
 await page.goto('/results');
 const fixture=JSON.parse(await readFile(new URL('../../../docs/fixtures/lunar-crystallize-reference.synthetic.json',import.meta.url),'utf8'));
 const original=JSON.stringify(fixture,null,3)+'\n';
 await page.locator('#importInput').setInputFiles({name:'original.json',mimeType:'application/json',buffer:Buffer.from(original)});
 await expect(page.locator('#documentNotice')).toContainText('打开不会运行模拟');
 expect(await page.evaluate(()=>window.GenshinDpsLab.getLastResult())).toBeNull();
 expect(await page.evaluate(()=>Object.keys(localStorage).filter(k=>k.startsWith('gidps:document:')))).toEqual([]);
 await page.locator('#energyModeInput').selectOption('full');
 const changed={...fixture,duration:120};
 await page.locator('#jsonEditor').fill(JSON.stringify(changed));
 await expect(page.locator('#documentNotice')).toContainText('自动保存');
 const saved=await page.evaluate(()=>localStorage.getItem(Object.keys(localStorage).find(k=>k.startsWith('gidps:document:'))!)!);
 expect(JSON.parse(saved).original.text).toBe(original);expect(JSON.parse(saved).verification).toBe('not-recomputed');
 await page.locator('#localCopiesButton').click();
 const recoveryDownload=page.waitForEvent('download');await page.locator('[data-local-copy]').first().click();
 const recovery=await recoveryDownload;const recoveryStream=await recovery.createReadStream();const recoveryChunks:Buffer[]=[];
 for await(const chunk of recoveryStream!)recoveryChunks.push(Buffer.from(chunk));
 expect(Buffer.concat(recoveryChunks).toString()).toBe(saved);
 expect(await page.evaluate(()=>window.GenshinDpsLab.getLastResult())).toBeNull();
 await page.locator('#importInput').setInputFiles({name:'edited.gidps.json',mimeType:'application/json',buffer:Buffer.from(saved)});
 await expect(page.locator('#documentNotice')).toContainText('尚未重新模拟');
 expect(await page.evaluate(()=>window.GenshinDpsLab.getConfig().duration)).toBe(120);
 await expect(page.locator('#energyModeInput')).toHaveValue('full');
 await page.locator('#jsonEditor').fill('{broken');
 await expect(page.locator('#documentNotice')).toContainText('编辑内容保留');
 await expect(page.locator('#jsonEditor')).toHaveValue('{broken');
});

