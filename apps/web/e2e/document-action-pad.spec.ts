test('new EC run exports strict witnesses and reopens without rerunning',async({page})=>{
 test.setTimeout(120000);
 const config=await readFile(new URL('../../../docs/fixtures/ec-event-steps.synthetic.json',import.meta.url),'utf8');
 await page.goto('/results');
 await page.locator('#importInput').setInputFiles({name:'ec.json',mimeType:'application/json',buffer:Buffer.from(config)});
 await expect(page.locator('#documentNotice')).toContainText('打开不会运行模拟');
 await page.locator('#runButton').click();
 await expect.poll(()=>page.evaluate(()=>window.GenshinDpsLab.getLastResult()?.totalDamage),{timeout:30000}).toBeGreaterThan(0);
 const originalDamage=await page.evaluate(()=>window.GenshinDpsLab.getLastResult()!.totalDamage);
 const download=page.waitForEvent('download');await page.locator('#exportRunButton').click();
 const file=await download;const stream=await file.createReadStream();const chunks:Buffer[]=[];for await(const chunk of stream!)chunks.push(Buffer.from(chunk));
 const text=Buffer.concat(chunks).toString();const raw=JSON.parse(text);
 expect(raw.format).toBe('gidps-simulation-record-v2');expect(raw.validation).toBe('event-steps-v1');
 expect(raw.result.result.schemaVersion).toBe('1.54.0-event-steps');expect(raw.result.evidence.propagationEvents.length).toBeGreaterThan(0);
 await page.locator('#importInput').setInputFiles({name:'new-ec.json',mimeType:'application/json',buffer:Buffer.from(text)});
 await expect(page.locator('#documentNotice')).toContainText('事件见证已严格校验');
 expect(await page.evaluate(()=>window.GenshinDpsLab.getLastResult()!.totalDamage)).toBe(originalDamage);
 expect(await page.locator('#simulationProgress').textContent()).toContain('未重新模拟');
 const forged=structuredClone(raw);forged.result.evidence.propagationEvents[0].operations.reverse();
 await page.locator('#importInput').setInputFiles({name:'forged.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(forged))});
 await expect(page.locator('#documentNotice')).toContainText('运行输入不完整');
 expect(await page.evaluate(()=>window.GenshinDpsLab.getLastResult())).toBeNull();
 await page.locator('.product-nav a[href="/calculator"]').click();
 const capture={schemaVersion:'calculator-event-v2',eventId:raw.result.result.damageEvents[0].id,eventStepResult:raw.result};
 await page.locator('#calc-import').setInputFiles({name:'witnessed-hit.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(capture))});
 await expect(page.getByTestId('replay-difference')).toHaveText('0');
});

test('source-defined Noelle Q and A calculate a 120-second window without multiplying the short sequence',async({page})=>{
 test.setTimeout(120000);
 const config=JSON.parse(await readFile(new URL('../../../docs/fixtures/noelle-q-normal-reference.json',import.meta.url),'utf8')) as SimConfig;
 config.timeline!.commands=[];
 await page.goto('/results');
 await page.locator('#importInput').setInputFiles({name:'noelle.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(config))});
 await expect(page.locator('#documentNotice')).toContainText('打开不会运行模拟');
 await page.locator('.product-nav a[href="/rotation"]').click();
 await page.locator('#padDuration').selectOption('120');
 await expect(page.locator('[data-pad-ability="noelle-burst"]')).toBeEnabled({timeout:30000});
 await page.locator('[data-pad-ability="noelle-burst"]').click();
 await expect(page.locator('[data-pad-ability="noelle-normal-1"]')).toBeEnabled({timeout:30000});
 await page.locator('[data-pad-ability="noelle-normal-1"]').click();
 await expect(page.locator('#rotation-list li')).toHaveCount(2);
 await expect(page.locator('#padStatus')).toContainText('当前 2 条指令',{timeout:30000});
 await page.screenshot({path:'/workspace/GIDPS-cloud/document-ui-20261021/noelle-action-pad.png',fullPage:true});
 await page.locator('#rotation-save').click();
 await expect.poll(()=>page.evaluate(()=>window.GenshinDpsLab.getLastResult()?.damageEvents.length),{timeout:30000}).toBe(3);
 const result=await page.evaluate(()=>window.GenshinDpsLab.getLastResult()!);
 expect(result.config.duration).toBe(120);
 const expected=[13.865514903092786,19.1476158185567,16.32499314185567];
 for(const [i,hit] of result.damageEvents.entries())expect(hit.finalDamage).toBeCloseTo(expected[i]!,9);
 expect(result.totalDamage).toBeCloseTo(expected.reduce((a,b)=>a+b,0),9);
 expect(result.dps).toBeCloseTo(result.totalDamage/120,9);
});
