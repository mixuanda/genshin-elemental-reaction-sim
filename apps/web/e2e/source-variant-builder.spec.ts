import { expect, test } from "@playwright/test";
import { readFile, writeFile } from "node:fs/promises";
import type { SourceHostResult } from "../../../packages/sim-core/src/source-host-wire";

test("selected source owns build handoff, form choice, isolated drafts and the actual execution", async ({ page }) => {
  test.setTimeout(90000);
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/builds");
  await page.locator("#build-character").selectOption("character:10000150");
  await expect(page.locator("#build-source-status")).toContainText("暂不提供");
  await expect(page.locator("#build-add-team")).toBeDisabled();
  await page.locator("#build-source-host").selectOption("stellar");
  await expect(page.locator("#build-source-form")).toHaveValue("odette");
  await page.locator("#build-add-team").click();
  await expect(page).toHaveURL(/\/source-simulation$/);
  await expect(page.locator("#source-host-variant")).toHaveValue("stellar");
  const builder = page.locator("#source-team-builder");
  await expect(builder).toContainText("a7dc4bf");
  await expect(builder.locator("[data-member-tab]")).toHaveCount(1);
  for (const key of ["aethercryo", "iansan", "ifa", "jahoda", "luminecryo", "odette", "prune"]) {
    await expect(builder.locator(`[data-add-character] option[value="${key}"]`)).toHaveCount(1);
  }
  await builder.locator('[data-quick-action="skill"]').click();
  await builder.locator('[data-draft-field="durationSeconds"]').fill("3");
  await builder.locator('[data-draft-field="durationSeconds"]').press("Tab");
  await builder.locator("[data-rotation-loop]").selectOption("count");
  await builder.locator('[data-rotation-field="count"]').fill("2");
  await builder.locator('[data-rotation-field="count"]').press("Tab");
  await builder.locator("[data-apply-script]").click();
  await expect(page.locator("#source-host-variant")).toHaveValue("stellar");
  const script = await page.locator("#source-host-config").inputValue();
  expect(script).toContain("# Source: stellar a7dc4bf");
  expect(script).toContain("odette skill;");
  expect(script).toContain("for let rotation = 0; rotation < 2; rotation = rotation + 1 {");
  const draftDownload = page.waitForEvent("download");
  await builder.locator("[data-export-draft]").click();
  const savedDraft = await readFile((await (await draftDownload).path())!, "utf8");
  expect(JSON.parse(savedDraft).source).toEqual({ hostVariant: "stellar", revision: "a7dc4bf4f5e18390035ca0333fb6eb1d5fac32bd" });
  await page.locator("#source-host-variant").selectOption("classic");
  await expect(builder).toContainText("b4ae769");
  await expect(builder.locator("[data-member-tab]")).toHaveCount(0);
  await builder.locator("[data-add-character]").selectOption("noelle");
  await builder.locator("[data-import-draft]").setInputFiles({ name: "stellar-draft.json", mimeType: "application/json", buffer: Buffer.from(savedDraft) });
  await expect(builder.locator(".source-team-builder__status")).toContainText("另一来源执行器");
  await expect(builder.locator("[data-member-tab]")).toHaveCount(1);
  await expect(builder.locator("[data-member-tab]")).toContainText("诺艾尔");
  await page.locator("#source-host-variant").selectOption("stellar");
  await expect(builder).toContainText("a7dc4bf");
  await expect(builder.locator("[data-member-tab]")).toContainText("奥黛塔");
  await expect(builder.locator(".source-team-builder__actions > li")).toHaveCount(1);
  await builder.locator("[data-rotation-loop]").selectOption("continuous");
  await builder.locator("[data-apply-script]").click();
  await expect(page.locator("#source-host-config")).toHaveValue(/while 1 \{/);
  await builder.locator("[data-import-draft]").setInputFiles({ name: "stellar-draft.json", mimeType: "application/json", buffer: Buffer.from(savedDraft) });
  await expect(builder.locator("[data-rotation-loop]")).toHaveValue("count");
  await expect(builder.locator('[data-rotation-field="count"]')).toHaveValue("2");
  await builder.locator("[data-apply-script]").click();
  expect(await page.locator("#source-host-config").inputValue()).toBe(script);
  await page.locator("#source-host-run").click();
  await expect(page.locator("#source-host-status")).toContainText("本次运行完成", { timeout: 60000 });
  const resultDownload = page.waitForEvent("download");
  await page.locator("#source-host-export").click();
  const result = JSON.parse(await readFile((await (await resultDownload).path())!, "utf8")) as SourceHostResult;
  expect(result.sourceCommit).toBe("a7dc4bf4f5e18390035ca0333fb6eb1d5fac32bd");
  expect(result.config).toBe(script);
  expect(result.applications.length).toBeGreaterThan(0);
  await writeFile("docs/validation/source-variant-builder-20260928.result.json", JSON.stringify(result, null, 2));
  await page.locator("#source-host-open-calculator").click();
  await expect(page.locator("#calc-source-host-capture")).toContainText("差值 0");

  await page.goto("/builds");
  await page.locator("#build-character").selectOption("character:10000005");
  await page.locator("#build-source-host").selectOption("stellar");
  await expect(page.locator("#build-source-status")).toContainText("请明确选择");
  await expect(page.locator("#build-add-team")).toBeDisabled();
  await page.locator("#build-source-form").selectOption("aethercryo");
  await expect(page.locator("#build-add-team")).toBeEnabled();
  expect(errors).toEqual([]);
});
