import { Buffer } from "node:buffer";
import { readFile } from "node:fs/promises";
import { expect, test } from "@playwright/test";
import type { SimConfig } from "@genshin-dps-lab/schemas";

test("visual rotation preserves real actor commands, cooldown waits and energy rejection without DSL", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  const fixture = JSON.parse(await readFile(new URL("../../../docs/fixtures/lunar-crystallize-reference.synthetic.json", import.meta.url), "utf8")) as SimConfig;
  fixture.meta.name = "可视化轮转合成输入";
  fixture.timeline!.commands = [];
  fixture.timeline!.legalityMode = "wait";
  Object.assign(fixture.timeline!.abilities[0]!, { cooldownFrames: 120, cancelFrame: 20, animationEndFrame: 30 });
  fixture.timeline!.abilities.push({ id: "h-q", actorId: "h", name: "合成爆发资格", kind: "burst", cooldownFrames: 180, cancelFrame: 30, animationEndFrame: 40, energyCost: 60 });
  await page.goto("/results");
  await page.locator("#importInput").setInputFiles({ name: "visual-rotation.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(fixture)) });
  await expect(page.locator("#notice")).toContainText(fixture.meta.name);
  await page.locator('.product-nav a[href="/rotation"]').click();
  await expect(page.locator("#rotation-dsl")).toBeHidden();
  await page.locator("#rotation-full-palette > summary").click();
  await expect(page.locator('[data-rotation-actor="h"] button').filter({ hasText: "重击" })).toBeDisabled();
  await page.locator('[data-visual-ability="h"]').click();
  await page.locator('[data-visual-ability="h"]').click();
  await page.locator('[data-visual-ability="g"]').click();
  await page.locator('[data-visual-ability="h-q"]').click();
  await expect(page.locator("#rotation-list li")).toHaveCount(6);
  await expect(page.locator('[data-visual-command="2"]')).toContainText("合成岩贡献者 · 切人");
  await page.locator('[data-move-down="3"]').click();
  await page.locator('[data-move-up="4"]').click();
  await page.locator('[data-remove="5"]').click();
  await page.locator('[data-visual-ability="h-q"]').click();
  await page.locator("#rotation-compile").click();
  await expect(page.locator('[data-visual-execution="1"]')).toHaveClass(/waited/);
  await expect(page.locator('[data-visual-execution="1"]')).toContainText("100f");
  await expect(page.locator('[data-visual-execution="5"]')).toHaveClass(/rejected/);
  await expect(page.locator('[data-visual-execution="5"]')).toContainText("起手能量 0 / 需要 60");
  await page.locator("#rotation-advanced-dsl > summary").click();
  await expect(page.locator("#rotation-dsl")).toHaveValue("action h for h\naction h for h\nswap g\naction g for g\nswap h\naction h-q for h");
  expect(errors).toEqual([]);
});
