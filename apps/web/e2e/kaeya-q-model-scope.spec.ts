import {expect,test} from '@playwright/test';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import type {SourceHostResult} from '../../../packages/sim-core/src/source-host-wire';
import {captureSourceHostHit,replaySourceHostHit} from '../../../packages/sim-core/src/source-host-capture';
const directory=process.env.GIDPS_KAEYA_SCOPE_EVIDENCE??'test-results/kaeya-q-scope';
test('Kaeya Q model scope remains visible in result and independent hit calculator without extra opening damage',async({page})=>{
 test.setTimeout(120000);await mkdir(directory,{recursive:true});
 const config=(await readFile(new URL('./fixtures/real-shatter/rotation-120.gcsim',import.meta.url),'utf8')).replace('duration=120','duration=8');
 await page.goto('/source-simulation');
 await page.locator('#source-host-config').evaluate(el=>{let p=el.closest('details');while(p){p.open=true;p=p.parentElement?.closest('details')??null;}});
 await page.locator('#source-host-config').fill(config);await page.locator('#source-host-seed').fill('12021');await page.locator('#source-host-variant').selectOption('classic');
 await page.locator('#source-host-run').click();
 await expect(page.locator('#source-host-status')).toContainText(/本次运行完成|失败/,{timeout:90000});
 expect(await page.locator('#source-host-status').textContent(),await page.locator('[data-diagnostic-json]').textContent()??'').toContain('本次运行完成');
 const notice=page.locator('[data-source-host-result-overview] [data-source-model-limit="kaeya-q"]');
 await expect(notice).toBeVisible();await expect(notice).toContainText('几何近似');
 await page.locator('#source-host-export').evaluate(el=>{el.closest('details')!.open=true;});
 const download=page.waitForEvent('download');await page.locator('#source-host-export').click();
 const r=JSON.parse(await readFile((await(await download).path())!,'utf8')) as SourceHostResult;
 await writeFile(`${directory}/short.capture.json`,JSON.stringify(r));
 const ids=new Set(r.calculations.filter(c=>c.request.actorKey==='kaeya'&&c.request.ability==='Glacial Waltz'&&c.request.kind==='damage').map(c=>c.request.id));
 const q=r.applications.filter(a=>ids.has(a.calculationId));
 expect(q.map(a=>a.frame)).toEqual([106,146,186,226,266,306,346,386,426,466]);
 await expect(notice.locator('[data-kaeya-q-observed]')).toContainText(`实际结算 ${q.length} 条 Q`);
 const originalTotal=r.applications.reduce((sum,a)=>sum+a.appliedDamage,0);
 expect(Number(await page.locator('[data-source-host-overview-total]').getAttribute('data-value'))).toBe(originalTotal);
 const hitIndex=r.applications.findIndex(a=>a.id===q[0]!.id);
 await page.locator('#source-host-hit-index').evaluate(el=>{let p=el.closest('details');while(p){p.open=true;p=p.parentElement?.closest('details')??null;}});
 await page.locator('#source-host-hit-index').fill(String(hitIndex));await page.locator('#source-host-open-calculator').click();
 await expect(page).toHaveURL(/\/calculator$/);
 await expect(page.locator('#calc-source-host-capture [data-source-model-limit="kaeya-q"]')).toBeVisible();
 await expect(page.locator('#calc-source-host-capture')).toContainText('单击重放一致不能验证');
 const replay=replaySourceHostHit(captureSourceHostHit(r,q[0]!.id));expect(replay.difference).toBe(0);
 await writeFile(`${directory}/ui-and-calculation.json`,JSON.stringify({hits:q.map(a=>({frame:a.frame,damage:a.rawDamage})),originalTotal,replayed:replay.difference,modelNotice:await page.locator('#calc-source-host-capture [data-source-model-limit="kaeya-q"]').textContent()},null,2));
});
