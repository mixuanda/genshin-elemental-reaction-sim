/** Shared entry for UI, JSON and calculation; each source group applies only to its explicit actions. */
export function prepareSourceCastDocument(document: CalculatorDocument): CalculatorDocument {
  document = prepareCynoDamageDocument(document);
  document = prepareKinichDamageDocument(document);
  document = prepareGamingDamageDocument(document);
  document = prepareXiaoDamageDocument(document);
  document = prepareDurinSkillDocument(document);
  document = prepareRawSourceStateDocument(document);
  document = prepareKachinaCastDocument(document);
  document = prepareObservedPlungeDocument(document);
  document = prepareTravelerHydroResolvedCastDocument(document);
  document = prepareIansanSwiftResolvedCastDocument(document);
  document = prepareObservedSpecialComponentDocument(document);
  document = prepareLinneaObservedDocument(document);
  document = prepareSandroneObservedLifecycleDocument(document);
  document = prepareNeferPhantasmCastDocument(document);
  document = prepareNeferObservedDocument(document);
  document = prepareTravelerCryoStateDocument(document);
  document = prepareTravelerCrossEntityCastDocument(document);
  document = prepareZibaiFiniteCastDocument(prepareObservedZibaiResourceDocument(document));
  document = prepareEntityFollowupCastDocument(document);
  document = prepareExtendedStanceCastDocument(document);
  document = prepareNoellePlungeCastDocument(document);
  document = prepareMixedSourceCastDocument(document);
  const previous = prepareHeldLifecycleCastDocument(prepareFiniteFollowupCastDocument(prepareCoordinatedCastDocument(prepareBatchFiniteCastDocument(prepareBatchPeriodicCastDocument(prepareBatchProjectileCastDocument(prepareTravelerCryoDocument(document)))))));
  const prepared = prepareTravelerMaleChargedCastDocument(preparePeriodicOrdinaryCastDocument(prepareObservedEntityCastDocument(prepareIdleStanceCastDocument(previous))));
  return prepareAlyoshaObservedDocument(prepareObservedCharacterResourceDocument(prepareObservedZibaiResourceDocument(prepared)));
}
