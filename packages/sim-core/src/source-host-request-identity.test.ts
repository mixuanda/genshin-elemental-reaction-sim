import { readFileSync } from "node:fs";
import { expect, it } from "vitest";
import { createSourceHostResult } from "./source-host-capture";
import { createSourceHostFormulaResolver } from "./source-host-formula";
import { sourceHostRequestsEqual } from "./source-host-request-identity";
import type { SourceHostResult } from "./source-host-wire";

const capture = JSON.parse(readFileSync(new URL("../../../docs/validation/action-opportunities-classic-xingqiu-20260929.capture.json", import.meta.url), "utf8")) as SourceHostResult;
const resolver = createSourceHostFormulaResolver();
for (const row of capture.calculations) {
  const response = JSON.parse(resolver.resolve(JSON.stringify(row.request)));
  if (response.error || response.value !== row.value) throw new Error("The retained numeric fixture must replay exactly.");
}
const reverseKeys = (value: unknown): unknown => Array.isArray(value) ? value.map(reverseKeys)
  : value !== null && typeof value === "object"
    ? Object.fromEntries(Object.entries(value).reverse().map(([key, child]) => [key, reverseKeys(child)])) : value;

it("compares every JSON field while ignoring object key order, never array order or values", () => {
  const original = { frame: 1, actor: 0, nested: { value: 0, ordered: [1, 2], opaque: { a: 3, b: 4 } } };
  expect(sourceHostRequestsEqual(original, reverseKeys(original))).toBe(true);
  for (const changed of [{ ...original, frame: 2 }, { ...original, actor: 1 },
    { ...original, extra: undefined }, { ...original, nested: { ...original.nested, ordered: [2, 1] } },
    { ...original, nested: { ...original.nested, opaque: { a: 4, b: 3 } } }])
    expect(sourceHostRequestsEqual(original, changed)).toBe(false);
  expect(sourceHostRequestsEqual(-0, 0)).toBe(false);
  expect(sourceHostRequestsEqual([1], { 0: 1 })).toBe(false);
});

it("accepts a fresh complete receipt with reordered object properties without altering its frame arrays", () => {
  // Current explanation diagnostics are regenerated by this API; the retained
  // archive and its old diagnostics are not rewritten by the test.
  expect(createSourceHostResult(reverseKeys(capture), resolver.calculations)).toEqual(createSourceHostResult(capture, resolver.calculations));
});

for (const field of ["frame", "actorIndex", "actorKey", "ability"] as const) it(`rejects native ${field} tampering even when numeric inputs and outputs match`, () => {
  const altered = structuredClone(capture);
  // A modifier without a damage application previously escaped the input-only
  // fallback: native and resolver still had the same input and returned value.
  const row = altered.calculations.find(row => row.request.kind === "character-modifier")!;
  if (field === "frame" || field === "actorIndex") row.request[field]++;
  else row.request[field] += "-forged";
  expect(() => createSourceHostResult(altered, resolver.calculations)).toThrow(/共享核心上下文不一致/);
});

it("rejects changed opaque request metadata rather than trusting only the scalar formula input", () => {
  const altered = structuredClone(capture);
  const row = altered.calculations.find(row => row.request.kind === "damage")!;
  if (row.request.kind !== "damage") throw new Error("A damage fixture is required.");
  row.request.rawAttack.forensic = { owner: 999, ordered: [2, 1] };
  expect(() => createSourceHostResult(altered, resolver.calculations)).toThrow(/共享核心上下文不一致/);
});
