import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

// Run after both source builds. The browser/core carries these fixed tables so
// a saved hit can be replayed offline without accepting caller-supplied values.
const root = fileURLToPath(new URL('../../../', import.meta.url));
const lanes = [
  ['source-host', 'b4ae769d7c1c1bce68fce5faf0b460c5b5b7f541'],
  ['source-host-stellar', 'a7dc4bf4f5e18390035ca0333fb6eb1d5fac32bd'],
];
const registry = {};
const inputs = [];
for (const [directory, commit] of lanes) {
  const base = `${root}/apps/web/public/${directory}`;
  const manifest = JSON.parse(readFileSync(`${base}/manifest.json`, 'utf8'));
  if (manifest.source.revision !== commit) throw new Error(`${directory}: fixed source revision mismatch`);
  const read = name => {
    const bytes = readFileSync(`${base}/${name}`);
    const sha256 = createHash('sha256').update(bytes).digest('hex');
    const artifact = (directory === 'source-host' ? manifest.artifacts : manifest.files).find(row => row.path === name);
    if (artifact?.sha256 !== sha256) throw new Error(`${directory}: ${name} differs from built manifest`);
    inputs.push({ path: `apps/web/public/${directory}/${name}`, sha256 });
    return JSON.parse(bytes.toString('utf8'));
  };
  const tableRegistry = read('talent-table-registry.json');
  const tables = Object.fromEntries(tableRegistry.tables.map(table => [table.tableId, table]));
  const sites = {};
  for (const site of read('talent-read-instrumentation.json').instrumented) {
    if (!tables[site.tableId] || sites[site.siteId]) throw new Error(`${directory}: invalid or duplicate instrumented site ${site.siteId}`);
    sites[site.siteId] = { tableId: site.tableId, indexExpressions: site.indexExpressions,
      ...(site.talentLevelIndices ? { talentLevelIndices: site.talentLevelIndices } : {}),
      ...(site.rangeSource ? { rangeSource: site.rangeSource } : {}) };
  }
  const expressionSites = {};
  for (const { siteId, ...site } of tableRegistry.expressionSites ?? []) {
    if (expressionSites[siteId] || site.termSiteIds.some(id => !sites[id]))
      throw new Error(`${directory}: invalid or duplicate talent expression ${siteId}`);
    expressionSites[siteId] = site;
  }
  registry[commit] = { tables, sites, expressionSites };
}
const target = `${root}/packages/sim-core/src/source-host-talent-tables.generated.ts`;
writeFileSync(target, '// Generated by packages/source-host/scripts/generate-talent-registry.mjs. Do not edit.\n'
  + '// Only table reads instrumented in the pinned source builds are included.\n'
  + 'import type { SourceHostTalentRegistry } from "./source-host-talent-table";\n'
  + `export const sourceHostTalentRegistry: Record<string, SourceHostTalentRegistry> = ${JSON.stringify(registry)};\n`);
console.log(JSON.stringify({ target, inputs, lanes: Object.fromEntries(Object.entries(registry).map(([commit, value]) => [commit, { tables: Object.keys(value.tables).length, sites: Object.keys(value.sites).length, expressionSites: Object.keys(value.expressionSites).length }])) }, null, 2));
